def fetcher(xfile) -> Fetch:
    """A Fetch over a parsed zone: the bytes an offset pointer names (``XFile.resolve``)."""

    def fetch(raw: int, size: int) -> bytes:
        target = xfile.resolve(raw)
        if target is None or target.kind != "data":
            raise ConvertError(f"offset pointer {raw:#010x}: names no loaded data")
        data = target.node[target.key]
        start = target.within
        if isinstance(data, list):
            start += sum(len(e["raw"]) for e in data[: target.index or 0])
            data = b"".join(e["raw"] for e in data)
        return bytes(data)[start : start + size]

    fetch.target = xfile.resolve  # type: ignore[attr-defined]
    return fetch


def _cmp_unit(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    """Angle in degrees between CMP words a and b (big-endian u32 arrays)."""

    def unpack(w: np.ndarray) -> np.ndarray:
        w = w.astype(np.int64)
        x = ((w & 0x7FF) ^ 0x400) - 0x400
        y = (((w >> 11) & 0x7FF) ^ 0x400) - 0x400
        z = (((w >> 22) & 0x3FF) ^ 0x200) - 0x200
        v = np.stack([x / 1023.0, y / 1023.0, z / 511.0], axis=1)
        n = np.linalg.norm(v, axis=1, keepdims=True)
        return v / np.maximum(n, 1e-9)

    dot = np.clip(np.sum(unpack(a) * unpack(b), axis=1), -1, 1)
    return np.degrees(np.arccos(dot))


def _ps3_data(surface: dict, key: str, off: int, size: int, fetch: Fetch) -> bytes | None:
    value = surface.get(key)
    if value is not None:
        return bytes(value)
    raw = _u32(surface["raw"], off, ">I")
    if raw == 0 or size == 0:
        return None
    return fetch(raw, size)


def _stream_layout(flags: int) -> tuple[int, int]:
    """(verts0 bytes, stream bytes) per vertex for PS3 flags."""
    v0 = 16 if flags & 1 == 0 else (8 if flags & 3 == 1 else 16)
    return v0, {0: 16, 1: 16, 2: 16, 3: 8, 5: 12, 7: 4}.get(flags & 7, 0)


def _decode_ps3(flags: int, verts0: bytes, stream: bytes, n: int) -> dict:
    """PS3 vertices -> arrays: q (s16 x 3) or xyz, sign, normal, tangent, uv, colour."""
    out: dict = {}
    if flags & 1 == 0:
        a = np.frombuffer(verts0, ">f4").reshape(n, 4)
        out["xyz"], out["sign"] = a[:, :3], a[:, 3]
    else:
        stride = 8 if flags & 3 == 1 else 16
        raw = np.frombuffer(verts0, np.uint8).reshape(n, stride)
        q = raw[:, :8].copy().view(">i2").reshape(n, 4)
        out["q"], out["sign"] = q[:, :3], q[:, 3]
        if stride == 16:
            nt = raw[:, 8:16].copy().view(">u4").reshape(n, 2)
            out["normal"], out["tangent"] = nt[:, 0], nt[:, 1]
    fmt = flags & 7
    s = np.frombuffer(stream, np.uint8)
    if fmt in (0, 1, 2, 5):
        width = 16 if fmt != 5 else 12
        s = s.reshape(n, width)
        out["normal"] = s[:, 0:4].copy().view(">u4")[:, 0]
        out["tangent"] = s[:, 4:8].copy().view(">u4")[:, 0]
        out["uv"] = s[:, 8:12].copy().view(">u4")[:, 0]
        if fmt != 5:
            out["colour"] = s[:, 12:16]
    elif fmt == 3:
        s = s.reshape(n, 8)
        out["uv"] = s[:, 0:4].copy().view(">u4")[:, 0]
        out["colour"] = s[:, 4:8]
    elif fmt == 7:
        out["uv"] = s.reshape(n, 4).copy().view(">u4")[:, 0]
    return out


#: Header byte ranges compared as data (pointers, memUsage excluded).
_HEADER_DATA = (
    (0x4, 0x8),
    (0x28, 0xA0),
    (0xA4, 0xAC),
    (0xB0, 0xD0),
    (0xD4, 0xE0),
    (0xE4, 0xE8),
    (0xEC, 0xF0),
)


def compare_xmodels(pc_xfile, ps3_xfile, pc_models: dict, ps3_models: dict) -> dict:
    """Convert every PC model whose name the PS3 zone also has and compare it with the PS3
    one field by field and vertex by vertex. Returns counts (docs/convert.md 12)."""
    pc_fetch, ps3_fetch = fetcher(pc_xfile), fetcher(ps3_xfile)
    pc_strings, ps3_strings = pc_xfile.script_strings, ps3_xfile.script_strings
    r: dict = {"models": 0, "surfaces": 0, "vertices": 0, "triangles": 0}
    diffs: dict[str, int] = {}
    worst: dict[str, float] = {"normal_deg": 0.0, "tangent_deg": 0.0, "position_steps": 0.0}
    hist = np.zeros(4, np.int64)  # position error in steps: 0, <=1, <=2, more

    def bad(key: str, n: int = 1) -> None:
        diffs[key] = diffs.get(key, 0) + n

    for name in sorted(set(pc_models) & set(ps3_models)):
        a, b = pc_models[name], ps3_models[name]
        res = convert_xmodel(a, pc_fetch, None).node
        r["models"] += 1
        ha, hb = res["header"], bytes(b["header"])
        for lo, hi in _HEADER_DATA:
            if ha[lo:hi] != hb[lo:hi]:
                bad(f"header {lo:#x}..{hi:#x}")
        if ha[0xE0:0xE4] != hb[0xE0:0xE4]:
            bad("header memUsage")
        bn_a = res["bone_names"] and np.frombuffer(res["bone_names"], ">u2")
        bn_b = b.get("bone_names")
        if bn_b is None and _u32(hb, 0x8, ">I") not in (0,):
            bn_b = ps3_fetch(_u32(hb, 0x8, ">I"), 2 * hb[4])
        if bn_a is not None and bn_b is not None:
            names_a = [pc_strings[i] for i in bn_a]
            names_b = [ps3_strings[i] for i in np.frombuffer(bytes(bn_b), ">u2")]
            if names_a != names_b:
                bad("bone names")
        for key, off, size in (
            ("parent_list", 0xC, hb[4] - hb[5]),
            ("quats", 0x10, 8 * (hb[4] - hb[5])),
            ("trans", 0x14, 16 * (hb[4] - hb[5])),
            ("part_classification", 0x18, hb[4]),
            ("base_mat", 0x1C, 0x20 * hb[4]),
            ("coll_surfs", 0xA0, 0x24 * _u32(hb, 0xA4, ">I")),
            ("bone_info", 0xAC, 0x2C * hb[4]),
            ("high_mip_bounds", 0xD0, 0x10 * hb[6]),
        ):
            theirs = b.get(key)
            if theirs is None and _u32(hb, off, ">I") not in (0,) and size:
                theirs = ps3_fetch(_u32(hb, off, ">I"), size)
            mine = res.get(key)
            if (mine or b"") != (bytes(theirs) if theirs is not None else b""):
                bad(key)
        mats_a = [_name(m.get("material")) for m in res["materials"] or ()]
        mats_b = [_name(m.get("material")) for m in b.get("materials") or ()]
        if mats_a != mats_b:
            bad("material names")
        pa, pb = res.get("phys_preset"), b.get("phys_preset")
        if isinstance(pa, dict) and isinstance(pb, dict):
            if (
                pa["header"][4:0x1C] + pa["header"][0x20:]
                != bytes(pb["header"])[4:0x1C] + bytes(pb["header"])[0x20:]
            ):
                bad("physPreset")
        elif _name(pa) != _name(pb):
            bad("physPreset name")
        if _collmaps_bytes(res.get("collmaps")) != _collmaps_bytes(b.get("collmaps")):
            bad("collmaps")
        for sa, sb in zip(res["surfs"] or (), b.get("surfs") or (), strict=True):
            _compare_surface(sa, sb, ps3_fetch, r, bad, worst, hist)
    r["differences"] = dict(sorted(diffs.items()))
    r["worst"] = worst
    r["position_error_steps"] = {
        "0": int(hist[0]),
        "<=1": int(hist[1]),
        "<=2": int(hist[2]),
        ">2": int(hist[3]),
    }
    return r


def _name(obj) -> str | None:
    if isinstance(obj, dict):
        return obj.get("name")
    return getattr(obj, "name", None)


def _collmaps_bytes(collmaps) -> bytes:
    out = b""
    for c in collmaps or ():
        out += bytes(c.get("geom_list") or b"")[:4] + bytes(c.get("geom_list") or b"")[8:]
        for g in c.get("geoms") or ():
            out += bytes(g["raw"])[4:]
            brush = g.get("brush")
            if brush:
                raw = bytes(brush["raw"])
                out += raw[:0x20] + raw[0x24:0x58]
                for side in brush.get("sides") or ():
                    out += bytes(side["raw"])[4:] + bytes(side.get("plane") or b"")
                out += bytes(brush.get("verts") or b"")
    return out


def _compare_surface(sa, sb, fetch, r, bad, worst, hist) -> None:
    ra, rb = sa["raw"], bytes(sb["raw"])
    r["surfaces"] += 1
    fa, fb = struct.unpack_from(">H", ra, 2)[0], struct.unpack_from(">H", rb, 2)[0]
    n = struct.unpack_from(">H", rb, 4)[0]
    tri = struct.unpack_from(">H", rb, 6)[0]
    r["vertices"] += n
    r["triangles"] += tri
    for lo, hi, what in (
        (0, 2, "surface tileMode, vertListCount"),
        (4, 8, "surface counts"),
        (0xC, 0x14, "surface vertInfo counts"),
        (0x34, 0x48, "surface partBits"),
        (0x48, 0x54, "surface posOffset"),
        (0x54, 0x58, "surface +0x54 and exponents"),
        (0x58, 0x5C, "surface constant colour"),
    ):
        if ra[lo:hi] != rb[lo:hi]:
            bad(what)
    if fa != fb:
        bad("surface flags")
        return
    v0, st = _stream_layout(fb)
    mine = _decode_ps3(fa, sa["verts0"] or b"", sa["vertex_stream"] or b"", n)
    theirs = _decode_ps3(
        fb,
        _ps3_data(sb, "verts0", 0x1C, v0 * n, fetch) or b"",
        _ps3_data(sb, "vertex_stream", 0x24, st * n, fetch) or b"",
        n,
    )
    if "q" in mine:
        d = np.abs(mine["q"].astype(np.int64) - theirs["q"].astype(np.int64)).max(axis=1)
        hist[0] += int(np.sum(d == 0))
        hist[1] += int(np.sum(d == 1))
        hist[2] += int(np.sum(d == 2))
        hist[3] += int(np.sum(d > 2))
        if n:
            worst["position_steps"] = max(worst["position_steps"], float(d.max()))
    elif not np.array_equal(mine["xyz"], theirs["xyz"]):
        bad("float positions")
    if not np.array_equal(mine["sign"], theirs["sign"]):
        bad("binormal sign")
    for key in ("normal", "tangent"):
        if n and key in mine:
            same = mine[key] == theirs[key]
            r[f"{key}_exact"] = r.get(f"{key}_exact", 0) + int(same.sum())
            if not same.all():
                worst[f"{key}_deg"] = max(
                    worst[f"{key}_deg"], float(_cmp_unit(mine[key], theirs[key]).max())
                )
    if not np.array_equal(mine.get("uv"), theirs.get("uv")):
        bad("uv")
    if "colour" in mine and not np.array_equal(mine["colour"], theirs["colour"]):
        bad("colour")
    tris = _ps3_data(sb, "tri_indices", 0x8, 6 * tri, fetch)
    if (sa["tri_indices"] or b"") != (tris or b""):
        bad("triangle indices")
    for key, off in (("verts_blend", 0x14), ("tension_data", 0x18)):
        mine_b = sa.get(key)
        if mine_b is None:
            continue
        theirs_b = _ps3_data(sb, key, off, len(mine_b), fetch)
        if mine_b != theirs_b:
            bad(key)
    la, lb = sa.get("vert_lists") or [], sb.get("vert_lists")
    if lb is None and rb[1] and _u32(rb, 0x2C, ">I"):
        lb = [
            {"raw": fetch(_u32(rb, 0x2C, ">I"), 12 * rb[1])[12 * i : 12 * i + 12]}
            for i in range(rb[1])
        ]
    for x, y in zip(la, lb or (), strict=False):
        if bytes(x["raw"])[:8] != bytes(y["raw"])[:8]:
            bad("rigid vert list")
        tx, ty = x.get("collision_tree"), y.get("collision_tree")
        if tx and ty:
            if tx["raw"][:0x18] + tx["raw"][0x18:0x1C] + tx["raw"][0x20:0x24] != (
                bytes(ty["raw"])[:0x1C] + bytes(ty["raw"])[0x20:0x24]
            ):
                bad("collision tree header")
            if (tx.get("nodes") or b"") != bytes(ty.get("nodes") or b"") or (
                tx.get("leafs") or b""
            ) != bytes(ty.get("leafs") or b""):
                bad("collision tree nodes, leafs")


# -- binding a converted model to a PS3 zone's assets -----------------------------------------


def asset_words(xfile, kind: str) -> dict[str, tuple[bytes, Any]]:
    """Asset name -> (alias word, node) for every asset of node kind ``kind`` (``"XModel"``,
    ``"Material"``, ``"PhysPreset"``) that a parsed zone holds behind an alias slot."""
    out: dict[str, tuple[bytes, Any]] = {}
    for key, (node, _) in sorted(xfile.refs.slots.items()):
        if isinstance(node, dict) and node.get("_t") == kind and node.get("name"):
            out.setdefault(node["name"], (struct.pack(">I", key + 1), node))
    return out


def bind(model: dict, materials: dict[str, tuple[bytes, Any]], presets: dict) -> None:
    """Point a converted model's materials (and physPreset) at a PS3 zone's assets of the
    same name (``asset_words``); a name the zone lacks stops with that name."""
    for element in model.get("materials") or ():
        name = _name(element.get("material"))
        if name not in materials:
            raise ConvertError(f"XModel {model.get('name')}: material {name!r} not in the zone")
        element["raw"], element["material"] = materials[name]
    preset = model.get("phys_preset")
    if preset is not None:
        name = _name(preset)
        if name not in presets:
            raise ConvertError(f"XModel {model.get('name')}: physPreset {name!r} not in the zone")
        header = bytearray(model["header"])
        header[0xE8:0xEC] = presets[name][0]
        model["header"] = bytes(header)
        model["phys_preset"] = presets[name][1]


def adopt(model: dict, stock: dict) -> dict:
    """Replace a stock PS3 model by a converted one in place and return the stock dict,
    now holding the converted model. The stock dict, its material elements and its
    physPreset are kept: in a PS3 zone the first model using a material loads it inline,
    and other assets' alias pointers name the fields of that model's ``materials`` array
    (identities are by node, docs/research/remap.md 8). Material names must agree surface
    by surface."""
    mine = [_name(m.get("material")) for m in model.get("materials") or ()]
    theirs = [_name(m.get("material")) for m in stock.get("materials") or ()]
    if mine != theirs:
        raise ConvertError(f"XModel {model.get('name')}: materials {mine} vs stock {theirs}")
    # collmaps: each BrushWrapper's planes (+0x5c) is an offset pointer to its first
    # side's plane on both platforms, which only the stock nodes can name; the converted
    # collmaps equal the stock ones in every other byte (compare_xmodels).
    keep = {k: stock.get(k) for k in ("materials", "phys_preset", "collmaps")}
    header = bytearray(model["header"])
    header[0xE8:0xF4] = bytes(stock["header"])[0xE8:0xF4]
    surfs = stock.get("surfs")
    if surfs is not None and model.get("surfs") is not None and len(surfs) == len(model["surfs"]):
        # Surfaces too keep their dicts: PS3 zones share vertex, index and collision data
        # between models by offset pointer.
        for old, new in zip(surfs, model["surfs"], strict=True):
            _in_place(old, new)
        model = {**model, "surfs": surfs}
    stock.clear()
    stock.update(model)
    stock.update(keep)
    stock["header"] = bytes(header)
    return stock


def _in_place(old: dict, new: dict) -> None:
    lists_old, lists_new = old.get("vert_lists"), new.get("vert_lists")
    if lists_old and lists_new and len(lists_old) == len(lists_new):
        for a, b in zip(lists_old, lists_new, strict=True):
            tree_a, tree_b = a.get("collision_tree"), b.get("collision_tree")
            if isinstance(tree_a, dict) and isinstance(tree_b, dict):
                tree_a.clear()
                tree_a.update(tree_b)
                b = {**b, "collision_tree": tree_a}
            a.clear()
            a.update(b)
        new = {**new, "vert_lists": lists_old}
    old.clear()
    old.update(new)
