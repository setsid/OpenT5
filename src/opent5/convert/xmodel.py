"""PC XModel -> PS3 XModel, node by node.

A PC model (``pc.PCXModelHandler``: XModel 0xfc, XSurface 0x44, GfxPackedVertex 32 bytes)
becomes the node the PS3 handler (``xfile/handlers/xmodel.py``: XModel 0xf8, XSurface
0x5c) writes. Rules, each checked on the 293 models PC and PS3 mp_nuked share
(``compare_xmodels``; docs/convert.md section 12):

- header: PC[0x0, 0x28) + four lodInfo of 28 bytes (PC 32: the trailing lod,
  smcIndexPlusOne, smcAllocBits and unused bytes are dropped) + lodDistAutoGenerated and 7
  bytes + PC[0xac, 0xe0) + 12 zero bytes + memUsage and flags + PC[0xec, 0xfc) (the PC
  ``bad`` word is dropped), every field swapped; memUsage per ``ps3_mem_usage``.
- surface flags: PC flags | 1 (quantised positions) | 4 when every vertex has the same
  colour (constant colour), which is then stored at XSurface +0x58 (0 otherwise).
  ``flags & 7`` picks the PS3 vertex format (docs/extract.md 3.2).
- packed positions: offset = (min + max) * 0.5 per axis in f32 (all 1732 quantised PS3
  surfaces); one exponent e for the three axes, the smallest e >= 0 with 2^e >= the
  largest half extent; s16 = round((p - offset) * 32768 / 2^e); binormal sign +1 ->
  32767, -1 -> -32768.
- normal, tangent: PC PackedUnitVec -> CMP 11:11:10 (``world.cmp_pack``); uv: the PC
  packed half pair is one u32, swapped; colour bytes B, G, R, A -> R, G, B, A.
- XSurface +0x54 is 0x4b on every quantised PS3 surface (meaning INFERRED: unknown).
- collSurfs: PS3 0x24 per surface, the PC collTris pointer and count dropped.
- everything else (bones, rigid vertex lists, collision trees, blend data, high mip
  bounds, collmaps, physPreset) has the PC layout and is swapped.

Bone names are script string indices: ``convert_xmodel`` takes a function mapping a PC
index to the target zone's. Materials are kept as the PC handler parsed them; a caller
splicing the model into a PS3 zone replaces each by the target's material (by name).
Data the PC zone shares by offset pointer is fetched through ``fetch`` and written
inline (the PS3 linker shares more, by content; sharing is an optimisation).
"""

from __future__ import annotations

import math
import struct
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any

import numpy as np

from opent5.convert.swap import swap_struct
from opent5.convert.world import ConvertError, cmp_pack, pc_unit_vectors
from opent5.xfile.constants import PTR_INLINE

PC_XMODEL = 0xFC
PS3_XMODEL = 0xF8
PC_XSURFACE = 0x44
PS3_XSURFACE = 0x5C
#: XSurface +0x54 on every quantised PS3 surface of mp_nuked (1819 of 1820; the one
#: unquantised surface has 0).
QUANTISED_MARK = 0x4B

FLAG_QUANTISED = 1
FLAG_SKINNED = 2
FLAG_CONSTANT_COLOUR = 4

PC_PACKED_VERTEX = np.dtype(
    [
        ("xyz", "<f4", 3),
        ("binormal_sign", "<f4"),
        ("colour", "u1", 4),
        ("uv", "<u4"),
        ("normal", "u1", 4),
        ("tangent", "u1", 4),
    ]
)

#: Fetch(raw pointer value, byte count) -> the bytes a PC offset pointer names.
Fetch = Callable[[int, int], bytes]


@dataclass
class ModelResult:
    node: dict
    notes: list[str] = field(default_factory=list)


def _u32(data: bytes, off: int, fmt: str = "<I") -> int:
    return struct.unpack_from(fmt, data, off)[0]


def xmodel_header(pc_header: bytes) -> bytes:
    """PS3 XModel header (0xf8) from a PC one (0xfc, little-endian)."""
    if len(pc_header) != PC_XMODEL:
        raise ConvertError(f"PC XModel header: expected {PC_XMODEL} bytes, found {len(pc_header)}")
    sw = swap_struct("XModel", pc_header)
    out = bytearray(sw[0:0x28])
    for i in range(4):
        base = 0x28 + 32 * i
        out += sw[base : base + 28]
    # 0x98: lodDistAutoGenerated (PC +0xa8) and 7 bytes, zero in all 293 mp_nuked models.
    out += bytes([sw[0xA8]]) + bytes(7)
    out += sw[0xAC:0xE0]
    # PS3 0xd4..0xdf: 12 bytes, zero in all 293 mp_nuked models; memUsage and flags then
    # sit at 0xe0 and 0xe4 (PC 0xe0, 0xe4); the PC ``bad`` word (+0xe8) has no PS3 place.
    out += bytes(12) + sw[0xE0:0xE8]
    out += sw[0xEC:PC_XMODEL]
    if len(out) != PS3_XMODEL:
        raise AssertionError(len(out))
    return bytes(out)


def quantise(xyz: np.ndarray) -> tuple[np.ndarray, int, np.ndarray]:
    """(offset f32[3], exponent, s16 positions) for one surface's float positions."""
    xyz = xyz.astype(np.float32)
    lo, hi = xyz.min(axis=0), xyz.max(axis=0)
    offset = ((lo + hi) * np.float32(0.5)).astype(np.float32)
    half = float(((hi - lo) * np.float32(0.5)).max())
    # 2^4 = 16 for a half extent of 16.000002 (p_us_table_art02 surface 3): a relative
    # tolerance of 1e-6 below a power of two keeps the smaller exponent.
    exp = max(0, math.ceil(math.log2(half * (1 - 1e-6)))) if half > 0 else 0
    scale = 32768.0 / (2.0**exp)
    q = np.round((xyz.astype(np.float64) - offset.astype(np.float64)) * scale)
    return offset, exp, np.clip(q, -32768, 32767).astype(">i2")


def _binormal(sign: np.ndarray) -> np.ndarray:
    return np.where(sign < 0, -32768, 32767).astype(">i2")


def surface_streams(
    verts: np.ndarray, pc_flags: int, quantise_positions: bool = True
) -> tuple[int, bytes, bytes, bytes, int]:
    """PS3 (flags, verts0, vertex stream, tail 0x48..0x5c, constant colour word) of one
    surface from its PC vertices."""
    n = len(verts)
    colours = verts["colour"]
    constant = n > 0 and bool(np.all(colours == colours[0]))
    flags = pc_flags & ~(FLAG_QUANTISED | FLAG_CONSTANT_COLOUR)
    if quantise_positions:
        flags |= FLAG_QUANTISED
    if constant and quantise_positions:
        # formats 4 and 6 (float positions, constant colour) load no vertex stream at all
        # (structs-map.md 9), so an unquantised surface keeps its colours.
        flags |= FLAG_CONSTANT_COLOUR
    else:
        constant = False
    # PC colours are D3DCOLOR bytes B, G, R, A; PS3 stream colours R, G, B, A (all 67
    # varying-colour surfaces) and the constant colour word 0xAARRGGBB (the PC u32 as is,
    # big-endian: PC bfbfbfff -> ffbfbfbf, 4 surfaces).
    colour_word = struct.unpack("<I", bytes(colours[0]))[0] if constant else 0
    colours = colours[:, [2, 1, 0, 3]]
    normal = cmp_pack(pc_unit_vectors(verts["normal"]))
    tangent = cmp_pack(pc_unit_vectors(verts["tangent"]))
    uv = verts["uv"].astype(">u4")
    fmt = flags & 7
    tail = bytearray(PS3_XSURFACE - 0x48)
    if quantise_positions:
        offset, exp, q = quantise(verts["xyz"])
        pos = np.empty((n, 4), ">i2")
        pos[:, :3] = q
        pos[:, 3] = _binormal(verts["binormal_sign"])
        struct.pack_into(">3f", tail, 0, *offset.tolist())
        tail[0xC] = QUANTISED_MARK
        tail[0xD:0x10] = bytes([exp, exp, exp])
        if fmt in (3, 7):
            rec = np.empty(n, [("p", ">i2", 4), ("n", ">u4"), ("t", ">u4")])
            rec["p"], rec["n"], rec["t"] = pos, normal, tangent
            verts0 = rec.tobytes()
        else:
            verts0 = pos.tobytes()
    else:
        rec = np.empty(n, [("p", ">f4", 3), ("s", ">f4")])
        rec["p"], rec["s"] = verts["xyz"], verts["binormal_sign"]
        verts0 = rec.tobytes()
    struct.pack_into(">I", tail, 0x10, colour_word)
    if fmt in (0, 1, 2):
        rec = np.empty(n, [("n", ">u4"), ("t", ">u4"), ("uv", ">u4"), ("c", "u1", 4)])
        rec["n"], rec["t"], rec["uv"], rec["c"] = normal, tangent, uv, colours
    elif fmt == 5:
        rec = np.empty(n, [("n", ">u4"), ("t", ">u4"), ("uv", ">u4")])
        rec["n"], rec["t"], rec["uv"] = normal, tangent, uv
    elif fmt == 3:
        rec = np.empty(n, [("uv", ">u4"), ("c", "u1", 4)])
        rec["uv"], rec["c"] = uv, colours
    elif fmt == 7:
        rec = uv
    else:
        raise ConvertError(f"XSurface flags {flags:#x}: format {fmt} has no stream rule")
    return flags, verts0, rec.tobytes(), bytes(tail), colour_word


def _target(fetch: Fetch | None, raw: int):
    target = getattr(fetch, "target", None)
    found = target(raw) if target is not None else None
    if found is None or found.kind != "data":
        raise ConvertError(f"offset pointer {raw:#010x}: names no loaded data")
    return found


def _shared_list(fetch: Fetch | None, raw: int, count: int) -> list:
    """The elements of a list of structs an offset pointer names (shared vertList)."""
    t = _target(fetch, raw)
    data = t.node[t.key]
    if not isinstance(data, list) or t.within:
        raise ConvertError(f"offset pointer {raw:#010x}: not the start of a struct list")
    return data[t.index or 0 : (t.index or 0) + count]


def _shared_node(fetch: Fetch | None, raw: int) -> dict:
    """The node an offset pointer names (a shared collision tree: its "raw" header)."""
    t = _target(fetch, raw)
    if t.key != "raw" or t.within:
        raise ConvertError(f"offset pointer {raw:#010x}: not the start of a struct")
    return t.node


def _inline(data: bytes | None) -> int:
    return PTR_INLINE if data else 0


def _pc_data(surface: dict, key: str, raw: int, size: int, fetch: Fetch | None) -> bytes | None:
    """A PC surface array: inline bytes, or the bytes an offset pointer names."""
    value = surface.get(key)
    if value is not None:
        return bytes(value)
    if raw in (0,):
        return None
    if fetch is None:
        raise ConvertError(f"XSurface {key}: offset pointer {raw:#010x} and no fetch")
    return fetch(raw, size)


def convert_surface(pc_surface: dict, fetch: Fetch | None = None, quantise_positions=True) -> dict:
    """One PC XSurface node -> a PS3 XSurface node (all data inline)."""
    raw = bytes(pc_surface["raw"])
    if len(raw) != PC_XSURFACE:
        raise ConvertError(f"PC XSurface: expected {PC_XSURFACE} bytes, found {len(raw)}")
    pc_flags = struct.unpack_from("<H", raw, 2)[0]
    vert_count = struct.unpack_from("<H", raw, 4)[0]
    tri_count = struct.unpack_from("<H", raw, 6)[0]
    blend_counts = struct.unpack_from("<4h", raw, 0x10)
    v = blend_counts
    verts_pc = _pc_data(pc_surface, "verts0", _u32(raw, 0x20), 32 * vert_count, fetch)
    tris = _pc_data(pc_surface, "tri_indices", _u32(raw, 0xC), 6 * tri_count, fetch)
    blend = _pc_data(
        pc_surface,
        "verts_blend",
        _u32(raw, 0x18),
        2 * (v[0] + 3 * v[1] + 5 * v[2] + 7 * v[3]),
        fetch,
    )
    tension = _pc_data(pc_surface, "tension_data", _u32(raw, 0x1C), 48 * sum(v), fetch)
    verts = np.frombuffer(verts_pc or b"", PC_PACKED_VERTEX)
    flags, verts0, stream, tail, _ = surface_streams(verts, pc_flags, quantise_positions)

    lists_out = None
    lists = pc_surface.get("vert_lists")
    list_count = raw[1]
    if lists is None and _u32(raw, 0x28) not in (0,) and list_count:
        if fetch is None:
            raise ConvertError("XSurface vertList: offset pointer and no fetch")
        lists = _shared_list(fetch, _u32(raw, 0x28), list_count)
    if lists is not None:
        lists_out = []
        for element in lists:
            rec = bytearray(swap_struct("XRigidVertList", element["raw"]))
            tree = element.get("collision_tree")
            out = {"_t": "XRigidVertList"}
            if tree is None and struct.unpack_from("<I", element["raw"], 8)[0] not in (0,):
                tree = _shared_node(fetch, struct.unpack_from("<I", element["raw"], 8)[0])
            if tree is not None:
                head = swap_struct("XSurfaceCollisionTree", tree["raw"])
                t = {"_t": "XSurfaceCollisionTree", "raw": head}
                t["nodes"] = swap_struct("u16", tree["nodes"]) if tree.get("nodes") else None
                t["leafs"] = swap_struct("u16", tree["leafs"]) if tree.get("leafs") else None
                out["collision_tree"] = t
                struct.pack_into(">I", rec, 8, PTR_INLINE)
            else:
                out["collision_tree"] = None
            out["raw"] = bytes(rec)
            lists_out.append(out)

    rec = bytearray(PS3_XSURFACE)
    rec[0] = raw[0]
    rec[1] = list_count
    struct.pack_into(">HHH", rec, 2, flags, vert_count, tri_count)
    struct.pack_into(">I", rec, 0x8, _inline(tris))
    struct.pack_into(">4h", rec, 0xC, *blend_counts)
    struct.pack_into(">I", rec, 0x14, _inline(blend))
    struct.pack_into(">I", rec, 0x18, _inline(tension))
    struct.pack_into(">I", rec, 0x1C, _inline(verts0))
    struct.pack_into(">I", rec, 0x24, _inline(stream))
    struct.pack_into(">I", rec, 0x2C, PTR_INLINE if lists_out else 0)
    rec[0x34:0x48] = _swap32(raw[0x30:0x44])
    rec[0x48:0x5C] = tail
    return {
        "_t": "XSurface",
        "raw": bytes(rec),
        "verts_blend": swap_struct("u16", blend) if blend else None,
        "tension_data": _swap32(tension) if tension else None,
        "verts0": verts0 or None,
        "vertex_stream": stream or None,
        "vert_lists": lists_out,
        "tri_indices": swap_struct("u16", tris) if tris else None,
    }


def _swap32(data: bytes) -> bytes:
    return np.frombuffer(data, "<u4").astype(">u4").tobytes()


def _brush_wrapper(raw: bytes) -> bytes:
    """BrushWrapper (0x60): cbrush_t's fields plus the planes pointer at +0x5c."""
    return swap_struct("cbrush_t", raw[:0x60])[:0x5C] + _swap32(raw[0x5C:0x60])


def _collmap(pc_collmap: dict) -> dict:
    """Collmap -> PhysGeomList -> PhysGeomInfo -> BrushWrapper: same layouts, swapped."""
    out: dict = {"_t": "Collmap", "raw": pc_collmap["raw"]}
    geom_list = pc_collmap.get("geom_list")
    out["geom_list"] = swap_struct("PhysGeomList", geom_list) if geom_list else None
    geoms = []
    for g in pc_collmap.get("geoms") or ():
        element: dict = {"_t": "PhysGeomInfo", "raw": swap_struct("PhysGeomInfo", g["raw"])}
        brush = g.get("brush")
        if brush is not None:
            b: dict = {"_t": "BrushWrapper", "raw": _brush_wrapper(brush["raw"])}
            sides = []
            for side in brush.get("sides") or ():
                if side.get("plane") is None:
                    raise ConvertError("BrushWrapper side: shared plane not supported")
                sides.append(
                    {
                        "_t": "cbrushside_t",
                        "raw": swap_struct("cbrushside_t", side["raw"]),
                        "plane": swap_struct("cplane_s", side["plane"]),
                    }
                )
            b["sides"] = sides or None
            b["verts"] = swap_struct("vec3", brush["verts"]) if brush.get("verts") else None
            if brush.get("planes"):
                raise ConvertError("BrushWrapper planes inline: the PS3 loader does not load them")
            element["brush"] = b
        else:
            element["brush"] = None
        geoms.append(element)
    out["geoms"] = geoms if pc_collmap.get("geoms") is not None else None
    return out


def convert_xmodel(
    pc_model: dict,
    fetch: Fetch | None = None,
    bone_name: Callable[[int], int] | None = None,
) -> ModelResult:
    """A parsed PC XModel node -> a PS3 XModel node (``xfile/handlers/xmodel.py`` keys).

    ``bone_name`` maps a PC script string index to the target zone's (identity when
    None). Materials and the physPreset are carried as parsed (nodes or links); the
    caller decides what they become in the target zone."""
    notes: list[str] = []
    pc_header = bytes(pc_model["header"])
    header = bytearray(xmodel_header(pc_header))
    bones, roots, surf_count = pc_header[4], pc_header[5], pc_header[6]
    out: dict = {"_t": "XModel", "name": pc_model.get("name")}

    def data(key: str, off: int, size: int) -> bytes | None:
        value = pc_model.get(key)
        if value is not None:
            return bytes(value)
        raw = _u32(pc_header, off)
        if raw == 0 or size == 0:
            return None
        if fetch is None:
            raise ConvertError(f"XModel {out['name']}: {key} is an offset pointer and no fetch")
        struct.pack_into(">I", header, off, PTR_INLINE)
        return fetch(raw, size)

    names = data("bone_names", 0x8, 2 * bones)
    if names is not None:
        idx = np.frombuffer(names, "<u2")
        if bone_name is not None:
            idx = np.array([bone_name(int(i)) for i in idx], dtype=np.uint16)
        out["bone_names"] = idx.astype(">u2").tobytes()
    else:
        out["bone_names"] = None
    out["parent_list"] = data("parent_list", 0xC, bones - roots)
    quats = data("quats", 0x10, 8 * (bones - roots))
    out["quats"] = swap_struct("u16", quats) if quats else None
    trans = data("trans", 0x14, 16 * (bones - roots))
    out["trans"] = _swap32(trans) if trans else None
    out["part_classification"] = data("part_classification", 0x18, bones)
    base_mat = data("base_mat", 0x1C, 0x20 * bones)
    out["base_mat"] = _swap32(base_mat) if base_mat else None
    surfs = pc_model.get("surfs")
    out["surfs"] = [convert_surface(s, fetch) for s in surfs] if surfs is not None else None
    if surfs is not None and len(surfs) != surf_count:
        raise AssertionError((len(surfs), surf_count))
    materials = pc_model.get("materials")
    out["materials"] = (
        [
            {"_t": "XModelMaterial", "raw": _swap32(m["raw"]), "material": m.get("material")}
            for m in materials
        ]
        if materials is not None
        else None
    )
    coll = pc_model.get("coll_surfs")
    if coll is not None:
        rows = []
        for c in coll:
            sw = swap_struct("XModelCollSurf_s", c["raw"])
            rows.append(sw[8:0x2C])
        out["coll_surfs"] = b"".join(rows)
        if any(c.get("coll_tris") for c in coll):
            notes.append(
                f"{sum(1 for c in coll if c.get('coll_tris'))} collision surfaces carry "
                "collTris, which the PS3 struct has no field for (dropped)"
            )
    else:
        out["coll_surfs"] = None
    bone_info = pc_model.get("bone_info")
    out["bone_info"] = swap_struct("XBoneInfo", bone_info) if bone_info else None
    mips = pc_model.get("high_mip_bounds")
    out["high_mip_bounds"] = swap_struct("XModelHighMipBounds", mips) if mips else None
    preset = pc_model.get("phys_preset")
    if isinstance(preset, dict):
        preset = dict(preset)
        preset["_t"] = "PhysPreset"
        preset["header"] = swap_struct("PhysPreset", preset["header"])
    out["phys_preset"] = preset
    collmaps = pc_model.get("collmaps")
    out["collmaps"] = [_collmap(c) for c in collmaps] if collmaps is not None else None
    if pc_model.get("phys_constraints") is not None:
        raise ConvertError(f"XModel {out['name']}: physConstraints not supported")
    out["phys_constraints"] = None
    struct.pack_into(">I", header, 0xE0, ps3_mem_usage(_u32(pc_header, 0xE0), surfs, out["surfs"]))
    out["header"] = bytes(header)
    return ModelResult(out, notes)


def ps3_mem_usage(pc_mem_usage: int, pc_surfs: list | None, ps3_surfs: list | None) -> int:
    """PS3 memUsage (+0xe0) from the PC one (+0xe0): PC - 4 (header 0xf8 vs 0xfc), then for
    each surface whose PC vertices are its own (not an offset pointer to another
    surface's): + 24 (XSurface 0x5c vs 0x44) + vertCount x (PS3 bytes per vertex - 32).
    Exact for 288 of the 289 mp_nuked models with surfaces; the other is the one surface
    PS3 leaves unquantised (mp_flag_american_vertical, +1440 = 180 vertices x 8)."""
    if pc_surfs is None or ps3_surfs is None:  # surfaces in another zone (name ",...")
        return pc_mem_usage
    total = pc_mem_usage - 4
    for pc_surface, s in zip(pc_surfs, ps3_surfs, strict=True):
        if pc_surface.get("verts0") is None:
            continue
        flags, n = struct.unpack_from(">HH", s["raw"], 2)
        v0, stream = _stream_layout(flags)
        total += 24 + n * (v0 + stream - 32)
    return total


